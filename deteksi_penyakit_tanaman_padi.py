# Cell 10 (Fixed Total): Visualisasi Heatmap Aktivasi ViT
from PIL import Image
from google.colab import files
import cv2
import numpy as np
import matplotlib.pyplot as plt

print("Upload 1 gambar daun padi untuk melihat area fokus ViT...")
uploaded = files.upload()

for filename in uploaded.keys():
    # 1. Load & Preprocess Gambar
    raw_img = Image.open(filename).convert('RGB')
    orig_img = np.array(raw_img)

    input_tensor = val_transform(raw_img).unsqueeze(0).to(device)

    # 2. Forward Pass & Ambil Feature Map dari Layer Terakhir
    features = []
    def hook_fn(module, input, output):
        features.append(output)

    handle = model.blocks[-1].register_forward_hook(hook_fn)

    model.eval()
    with torch.no_grad():
        output = model(input_tensor)
        probabilities = torch.nn.functional.softmax(output[0], dim=0)

    handle.remove()

    # 3. Prediksi
    top_prob, top_catid = torch.topk(probabilities, 1)
    pred_label = class_names[top_catid[0].item()]
    conf = top_prob[0].item() * 100

    # 4. Ekstrak Heatmap dari Feature Map (14x14 Patch Grid)
    feat = features[0] # Shape: [1, 197, 768]

    # Ambil token patch (abaikan token [CLS] di index 0) -> Shape: [196, 768]
    patch_feat = feat[0, 1:, :]

    # Rata-rata kekuatan aktivasi di sepanjang channel (768) -> Shape: [196]
    heatmap_1d = patch_feat.abs().mean(dim=-1).cpu().numpy()

    # Reshape persis ke grid 14x14
    heatmap = heatmap_1d.reshape(14, 14)

    # Normalisasi nilai (0 sampai 1)
    heatmap = (heatmap - heatmap.min()) / (heatmap.max() - heatmap.min() + 1e-8)

    # Resize Heatmap ke ukuran gambar asli
    heatmap_resized = cv2.resize(heatmap, (orig_img.shape[1], orig_img.shape[0]))

    # Warna Heatmap (Colormap JET: Merah = Fokus Tinggi, Biru = Rendah)
    heatmap_colored = cv2.applyColorMap(np.uint8(255 * heatmap_resized), cv2.COLORMAP_JET)
    heatmap_colored = cv2.cvtColor(heatmap_colored, cv2.COLOR_BGR2RGB)

    # Combine (Overlay) Gambar + Heatmap
    overlay = cv2.addWeighted(orig_img, 0.6, heatmap_colored, 0.4, 0)

    # 5. Tampilkan Gambar
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))

    axes[0].imshow(orig_img)
    axes[0].set_title("Gambar Asli")
    axes[0].axis('off')

    axes[1].imshow(heatmap_colored)
    axes[1].set_title("Heatmap Aktivasi ViT")
    axes[1].axis('off')

    axes[2].imshow(overlay)
    axes[2].set_title(f"Prediksi: {pred_label}\nConfidence: {conf:.2f}%")
    axes[2].axis('off')

    plt.tight_layout()
    plt.show()