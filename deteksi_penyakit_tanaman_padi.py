# Cell 9: Visualisasi Attention Map pada Gambar
import cv2
import numpy as np
import matplotlib.pyplot as plt

def generate_attention_map(model, input_tensor):
    model.eval()
    # Mengambil bobot attention dari layer Transformer terakhir
    # Pada ViT timm, biasanya tersimpan di blok terakhir
    attention_maps = []

    def hook_fn(module, input, output):
        # Mengambil matriks attention
        attention_maps.append(output)

    # Pasang hook pada layer attention terakhir
    target_layer = model.blocks[-1].attn
    handle = target_layer.register_forward_hook(hook_fn)

    with torch.no_grad():
        _ = model(input_tensor)

    handle.remove()
    return attention_maps

