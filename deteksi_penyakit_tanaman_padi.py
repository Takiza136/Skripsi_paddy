# Cell 3: Data Pipeline & DataLoaders
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, random_split
from torchvision import transforms, datasets

# Path folder train_images hasil extract
data_dir = 'paddy_data/train_images'

# Transformasi & Augmentasi khusus input Vision Transformer
train_transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.RandomHorizontalFlip(),
    transforms.RandomRotation(15),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
])

val_transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
])

# Load dataset utama
full_dataset = datasets.ImageFolder(root=data_dir)
class_names = full_dataset.classes
print(f"Total gambar ditemukan: {len(full_dataset)}")
print(f"Jumlah kelas ({len(class_names)}): {class_names}")

# Pembagian data 80% Train, 20% Val
train_size = int(0.8 * len(full_dataset))
val_size = len(full_dataset) - train_size

train_dataset, val_dataset = random_split(full_dataset, [train_size, val_size])

# Terapkan transformasi
train_dataset.dataset.transform = train_transform
val_dataset.dataset.transform = val_transform

# DataLoader
train_loader = DataLoader(train_dataset, batch_size=32, shuffle=True, num_workers=2)
val_loader = DataLoader(val_dataset, batch_size=32, shuffle=False, num_workers=2)

print(f"Data Train: {len(train_dataset)} | Data Val: {len(val_dataset)}")

# Cell 4: Load Arsitektur ViT
import timm

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

# Membuat model ViT dengan jumlah output kelas sesuai dataset padi
model = timm.create_model('vit_base_patch16_224', pretrained=True, num_classes=len(class_names))
model = model.to(device)

# Loss Function & Optimizer (AdamW adalah standar terbaik untuk ViT)
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4, weight_decay=0.01)

print("Model ViT berhasil dimuat ke:", device)

# Cell 5: Training Loop
import time

epochs = 5  # Kamu bisa ubah ke 10 atau lebih nanti

print("Mulai Proses Training ViT...\n" + "="*40)

for epoch in range(epochs):
    start_time = time.time()

    # --- TRAINING PHASE ---
    model.train()
    running_loss = 0.0
    correct_train = 0
    total_train = 0

    for images, labels in train_loader:
        images, labels = images.to(device), labels.to(device)

        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

        running_loss += loss.item() * images.size(0)
        _, preds = torch.max(outputs, 1)
        correct_train += torch.sum(preds == labels.data)
        total_train += labels.size(0)

    train_loss = running_loss / total_train
    train_acc = correct_train.double() / total_train

    # --- VALIDATION PHASE ---
    model.eval()
    val_loss = 0.0
    correct_val = 0
    total_val = 0

    with torch.no_grad():
        for images, labels in val_loader:
            images, labels = images.to(device), labels.to(device)
            outputs = model(images)
            loss = criterion(outputs, labels)

            val_loss += loss.item() * images.size(0)
            _, preds = torch.max(outputs, 1)
            correct_val += torch.sum(preds == labels.data)
            total_val += labels.size(0)

    val_loss = val_loss / total_val
    val_acc = correct_val.double() / total_val

    elapsed = time.strftime("%H:%M:%S", time.gmtime(time.time() - start_time))

    print(f"Epoch [{epoch+1}/{epochs}] | Waktu: {elapsed}")
    print(f"  Train Loss: {train_loss:.4f} | Train Acc: {train_acc*100:.2f}%")
    print(f"  Val Loss:   {val_loss:.4f} | Val Acc:   {val_acc*100:.2f}%\n")

# Cell 6: Simpan Model Weights
